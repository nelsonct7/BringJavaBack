public class Binary {
    public static void main(String[] args) {
        int binary1 = 0b10;
        System.out.println("Binary number " + binary1);
        int hexa=0x101;
        System.out.println("Hexa decimal number "+hexa);
        int lengthyNumber=10_00_00_0000;
        System.out.println("Lengthy number formatted "+lengthyNumber);
    }
}
